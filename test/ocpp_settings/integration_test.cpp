static ocpp_config_t connection() {
    ocpp_config_t config;
    strcpy(config.backendUrl, "wss://backend.example/ocpp");
    strcpy(config.chargePointId, "AT*INC*E910001");
    return config;
}

static std::string change(const char* key, const char* value) {
    JsonDocument request;
    request["key"] = key;
    request["value"] = value;
    BackendConfigurationOperation operation;
    operation.processReq(request.as<JsonObject>());
    return (*operation.createConf())["status"].as<std::string>();
}

int main() {
    const auto config = connection();
    BackendSettingsV1 legacy;
    legacy.heartbeatSeconds = 123;
    legacy.meterSeconds = 17;
    legacy.operative = 0;
    strcpy(legacy.backendUrl, config.backendUrl);
    strcpy(legacy.chargePointId, config.chargePointId);
    storage.assign(reinterpret_cast<uint8_t*>(&legacy), reinterpret_cast<uint8_t*>(&legacy) + sizeof(legacy));
    load_backend_settings(config);
    assert(backendSettings.heartbeatSeconds == 123 && backendSettings.meterSeconds == 17);
    assert(backendSettings.operative == 0);
    assert(backendSettings.transactionMessageAttempts == 3 && backendSettings.transactionMessageRetrySeconds == 60);

    for (const char* key : {"HeartbeatInterval", "MeterValueSampleInterval", "TransactionMessageAttempts", "TransactionMessageRetryInterval", "ConnectionTimeOut"})
        MicroOcpp::configurations[key].reset(new MicroOcpp::Configuration());
    assert(change("TransactionMessageAttempts", "7") == "Accepted");
    assert(change("TransactionMessageRetryInterval", "15") == "Accepted");
    assert(backendSettings.heartbeatSeconds == 123 && backendSettings.meterSeconds == 17 && backendSettings.operative == 0);
    assert(MicroOcpp::configurations["TransactionMessageAttempts"]->value == 7);
    backendSettings = BackendSettings{};
    load_backend_settings(config);
    assert(backendSettings.transactionMessageAttempts == 7 && backendSettings.transactionMessageRetrySeconds == 15);
    assert(backendSettings.heartbeatSeconds == 123 && backendSettings.meterSeconds == 17 && backendSettings.operative == 0);

    const auto saved = storage;
    writeOk = false;
    assert(change("TransactionMessageAttempts", "8") == "Rejected");
    assert(storage == saved && backendSettings.transactionMessageAttempts == 7);
    assert(MicroOcpp::configurations["TransactionMessageAttempts"]->value == 7);
    writeOk = true;
    assert(change("TransactionMessageAttempts", "0") == "Rejected");
    assert(change("ConnectionTimeOut", "300") == "Rejected");
    assert(change("AuthorizationKey", "000102030405060708090a0b0c0d0e0f") == "NotSupported");
    assert(storage == saved);

    assert(change("HeartbeatInterval", "60") == "Accepted");
    assert(change("MeterValueSampleInterval", "0") == "Accepted");
    assert(backendSettings.transactionMessageAttempts == 7 && backendSettings.operative == 0);
    authoritative = false;
    assert(change("TransactionMessageAttempts", "9") == "Rejected");
    authoritative = true;
    s_resetPending = true;
    assert(change("TransactionMessageAttempts", "9") == "Rejected");
    s_resetPending = false;

    auto other = config;
    strcpy(other.chargePointId, "OTHER");
    load_backend_settings(other);
    assert(backendSettings.heartbeatSeconds == 60 && backendSettings.meterSeconds == 60);
    assert(backendSettings.operative == 1 && backendSettings.transactionMessageAttempts == 3);
    storage.assign(5, 0xff);
    load_backend_settings(config);
    assert(backendSettings.heartbeatSeconds == 60 && backendSettings.transactionMessageRetrySeconds == 60);
    puts("PASS: production configuration handler, legacy NVS migration, persistence and failure paths");
}
