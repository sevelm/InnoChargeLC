class Preferences {
public:
    bool begin(const char*, bool) { return true; }
    size_t getBytesLength(const char*) { return storage.size(); }
    size_t getBytes(const char*, void* out, size_t size) {
        if (size != storage.size()) return 0;
        memcpy(out, storage.data(), size);
        return size;
    }
    size_t putBytes(const char*, const void* input, size_t size) {
        if (!writeOk) return 0;
        const uint8_t* bytes = static_cast<const uint8_t*>(input);
        storage.assign(bytes, bytes + size);
        return size;
    }
    void end() {}
};

